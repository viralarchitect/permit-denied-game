func PlateColor(plates int) color.RGBA {
	switch plates {
	case 4:
		return ColPaint
	case 3:
		return ColPrimer
	case 2:
		return ColRust
	default:
		return ColFrame
	}
}

func mix(a, b color.RGBA, t float64) color.RGBA {
	if t < 0 {
		t = 0
	}
	if t > 1 {
		t = 1
	}
	return color.RGBA{
		R: uint8(float64(a.R)*(1-t) + float64(b.R)*t),
		G: uint8(float64(a.G)*(1-t) + float64(b.G)*t),
		B: uint8(float64(a.B)*(1-t) + float64(b.B)*t),
		A: 255,
	}
}
